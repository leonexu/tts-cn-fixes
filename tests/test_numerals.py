def test_numerals() -> None:
    for src, want in CASES:
        got = normalize_arabic_numerals(src)
        assert got == want, f"src={src!r}\n  want={want!r}\n got ={got!r}"


def test_idempotent() -> None:
    for src, _ in CASES:
        once = normalize_arabic_numerals(src)
        assert normalize_arabic_numerals(once) == once, f"非幂等: {once!r}"


def test_funnel_order() -> None:
    # 生产漏斗顺序：数字归一化 → 多音字规则（数字产物「十航代码」仍命中行规则）
    assert apply_polyphone_substitutions(normalize_arabic_numerals("写10行代码")) == "写十航代码"
