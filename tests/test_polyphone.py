# -*- coding: utf-8 -*-
"""确定性规则 battery——每条实证判例一个用例（含误读回归锚）。"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from ttscnfix import apply_polyphone_substitutions  # noqa: E402

CASES = [
    # 行 háng（行列义）：数量词+代码类名词/没写（成片实拍「一行代码」读 xíng）
    ("一行代码都没写", "一航代码都没写"),
    ("这个文件有三百行文字", "这个文件有三百航文字"),
    ("银行不行了", "银行不行了"),            # háng 零歧义常见词不碰
    ("方案可行性一般", "方案可行性一般"),      # 可行 xíng 未实证误读，不碰
    # 行情（零歧义词钉死：LLM 也误判过 xíng）
    ("他把半年行情摊开讲", "他把半年航情摊开讲"),
    ("看最新行情帖报到多少", "看最新航情帖报到多少"),
    ("接单的行情在跌", "接单的航情在跌"),
    # 命令行（零歧义词钉死：克隆音色读「命令 xíng 操作」）
    ("用命令行操作", "用命令航操作"),
    ("在命令行里跑", "在命令航里跑"),
    # 同行（同业者 tóngháng → 同航；伴行义负向豁免）
    ("认识了很多同行", "认识了很多同航"),
    ("我们一路同行", "我们一路同行"),
    ("跟他结伴同行", "跟他结伴同行"),
    # 行不通/行得通（可行义 xíng 动补框架 → 形）
    ("这套打法直接搬到国内行不通", "这套打法直接搬到国内形不通"),
    ("这条路行得通吗", "这条路形得通吗"),
    # 还 huán（归还义）→ 环
    ("把工具还给他", "把工具环给他"),
    ("把钱还了", "把钱环了"),
    ("还是这样", "还是这样"),      # hái 义不在豁免集（LLM 层管反向）
    # 数 shǔ 计数义成语/口语 → 属
    ("数不胜数", "属不胜数"),      # 首字规则钉死；尾字待 LLM 层（无回调时放行）
    ("数不清有多少", "属不清有多少"),
    ("这些数对不上", "这些数对不上"),  # shù 名词义不命中
    # 得 děi 能愿高频 → 必须（同义改写，无同音字）
    ("这个工具得真用一遍才知道", "这个工具必须真用一遍才知道"),
    ("得先跑通再优化", "必须先跑通再优化"),
    ("取得真经", "取得真经"),      # 前接取得豁免
    ("觉得真不错", "觉得真不错"),  # 前接觉得豁免
    ("记得先备份", "记得先备份"),  # 前接记得豁免
]


def test_rules() -> None:
    for src, want in CASES:
        got = apply_polyphone_substitutions(src)
        assert got == want, f"src={src!r}\n  want={want!r}\n  got ={got!r}"


def test_empty_passthrough() -> None:
    assert apply_polyphone_substitutions("") == ""
